"""Response actions. Every action is written to an audit log that Splunk can ingest.

Containment actions are staged, not executed: the IP blocklist and pf firewall rules
are generated for an analyst to apply, and account lock commands are written out
rather than run. Automation that can lock out real users or block real traffic
should always have a human approval step until it has been proven safe.
"""

import json
import os
from datetime import datetime
from urllib.request import Request, urlopen


class ActionRunner:
    def __init__(self, out_dir):
        self.out = out_dir
        self.tickets_dir = os.path.join(out_dir, "tickets")
        os.makedirs(self.tickets_dir, exist_ok=True)
        self.blocklist = os.path.join(out_dir, "blocklist.txt")
        self.pf_rules = os.path.join(out_dir, "pf_block_rules.conf")
        self.lock_file = os.path.join(out_dir, "accounts_to_lock.sh")
        self.audit_log = os.path.join(out_dir, "response_actions.log")
        self.webhook = os.environ.get("SOC_WEBHOOK_URL")

    # ---------- audit ----------
    def audit(self, incident_id, action, target, result, severity, detections):
        entry = {
            "time": datetime.now().astimezone().isoformat(timespec="seconds"),
            "incident_id": incident_id,
            "action": action,
            "target": target,
            "result": result,
            "severity": severity,
            "detections": detections,
        }
        with open(self.audit_log, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry) + "\n")

    # ---------- containment ----------
    def block_ip(self, ip, incident_id):
        existing = set()
        if os.path.exists(self.blocklist):
            with open(self.blocklist, encoding="utf-8") as f:
                existing = {line.split("#")[0].strip() for line in f if line.strip()}
        if ip in existing:
            return "already blocked"
        with open(self.blocklist, "a", encoding="utf-8") as f:
            f.write(f"{ip}  # {incident_id} {datetime.now():%Y-%m-%d %H:%M}\n")
        new_file = not os.path.exists(self.pf_rules)
        with open(self.pf_rules, "a", encoding="utf-8") as f:
            if new_file:
                f.write("# pf firewall rules generated by Automated Incident Response\n"
                        "# Staged for review. Nothing here is loaded automatically.\n")
            f.write(f"block drop quick from {ip} to any  # {incident_id}\n")
        return "added to blocklist and pf rules"

    def lock_account(self, user, incident_id):
        existing = ""
        if os.path.exists(self.lock_file):
            with open(self.lock_file, encoding="utf-8") as f:
                existing = f.read()
        if f"usermod -L {user} " in existing:
            return "already staged"
        new_file = not existing
        with open(self.lock_file, "a", encoding="utf-8") as f:
            if new_file:
                f.write("#!/bin/sh\n# Account lock commands staged for analyst approval.\n"
                        "# Run on the affected Linux host only after confirming the incident.\n")
            f.write(f"usermod -L {user}   # lock password   ({incident_id})\n")
            f.write(f"pkill -KILL -u {user}   # end active sessions\n")
        return "lock command staged for approval"

    # ---------- ticketing ----------
    def create_ticket(self, incident_id, incident, enrichment, assessment, actions_taken):
        ind = incident["indicator"]
        lines = [
            f"# {incident_id}: {assessment['title']} ({ind})",
            "",
            "| | |",
            "|---|---|",
            f"| **Severity** | {assessment['severity']} (risk {assessment['risk']}/100) |",
            f"| **Status** | {_status(actions_taken)} |",
            f"| **Created** | {datetime.now():%Y-%m-%d %H:%M:%S} |",
            f"| **Indicator** | `{ind}` ({incident['indicator_type']}) |",
            f"| **Detections** | {', '.join(incident['detections'])} |",
            f"| **MITRE ATT&CK** | {', '.join(assessment['mitre'])} |",
            "",
            "## Enrichment",
            "",
        ]
        if incident["indicator_type"] == "ip":
            lines += [
                f"- Internal address: {'yes' if enrichment.get('internal') else 'no'}",
                f"- Allowlisted: {'yes' if enrichment.get('allowlisted') else 'no'}",
                f"- Reputation score: {enrichment.get('reputation', 0)}/100"
                + (f" ({', '.join(enrichment['tags'])})" if enrichment.get("tags") else ""),
                f"- Intel sources: {', '.join(enrichment['sources']) or 'none'}",
            ]
            if enrichment.get("documentation_range"):
                lines.append("- Note: RFC 5737 documentation range, used as a stand-in attacker in this lab")
        else:
            lines.append("- Local user account; no external enrichment applies")

        lines += ["", "## Evidence", ""]
        for name, rows in incident["detections"].items():
            lines.append(f"**{name}** ({len(rows)} result{'s' if len(rows) != 1 else ''})")
            lines.append("")
            for row in rows[:5]:
                shown = {k: v for k, v in row.items() if not k.startswith("_") or k == "_time"}
                shown.pop("severity", None)
                shown.pop("mitre", None)
                lines.append("- " + "; ".join(f"{k}={_fmt(v)}" for k, v in shown.items()))
            if len(rows) > 5:
                lines.append(f"- ...and {len(rows) - 5} more")
            lines.append("")

        lines += ["## Automated actions", ""]
        for action, target, result in actions_taken:
            lines.append(f"- **{action}** {target or ''}: {result}")
        lines += ["", "## Analyst next steps", ""]
        for i, step in enumerate(dict.fromkeys(assessment["steps"]), 1):
            lines.append(f"{i}. {step}")
        lines.append("")

        md_path = os.path.join(self.tickets_dir, f"{incident_id}.md")
        with open(md_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        with open(os.path.join(self.tickets_dir, f"{incident_id}.json"), "w", encoding="utf-8") as f:
            json.dump({
                "id": incident_id, "title": assessment["title"], "severity": assessment["severity"],
                "risk": assessment["risk"], "indicator": ind, "indicator_type": incident["indicator_type"],
                "detections": list(incident["detections"]), "mitre": assessment["mitre"],
                "enrichment": enrichment, "actions": [list(a) for a in actions_taken],
                "evidence": incident["detections"],
            }, f, indent=2, default=list)
        return md_path

    # ---------- notification ----------
    def notify(self, incident_id, assessment, indicator):
        text = (f"[{assessment['severity'].upper()}] {incident_id}: {assessment['title']} "
                f"from {indicator} (risk {assessment['risk']}/100)")
        if not self.webhook:
            return "console only (set SOC_WEBHOOK_URL to send to Slack or Teams)"
        try:
            req = Request(self.webhook, data=json.dumps({"text": text}).encode(),
                          headers={"Content-Type": "application/json"})
            urlopen(req, timeout=10).close()
            return "sent to webhook"
        except Exception as e:
            return f"webhook failed: {e}"


def _status(actions_taken):
    staged = [a for a in actions_taken if a[0] in ("block_ip", "lock_account") and not str(a[2]).startswith("skipped")]
    if staged:
        return "Containment staged automatically, awaiting analyst review"
    return "Escalated to analyst, no automatic containment"


def _fmt(v):
    if isinstance(v, list):
        return ", ".join(str(x) for x in v)
    return str(v)
